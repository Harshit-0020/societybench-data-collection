def clean_and_parse_date(date_str):
    # Remove 'Updated:' prefix (case-insensitive)
    date_str = re.sub(r'^(Updated:\s*)', '', date_str, flags=re.IGNORECASE).strip()
    # Remove timezone indicators like 'IST'
    date_str = re.sub(r'\s*IST\s*$', '', date_str).strip()
    # Strip any time component to focus on the date part (e.g., 'Oct 29, 2026, 11:52' -> 'Oct 29, 2026')
    if ',' in date_str:
        date_parts = date_str.split(',')
        if len(date_parts) >= 2:
            date_str = (date_parts[0] + ',' + date_parts[1]).strip()

    # Attempt to match multiple standard date patterns
    formats_to_try = [
        '%b %d, %Y',   # Oct 29, 2026
        '%B %d, %Y',   # October 29, 2026
        '%d %B %Y',    # 29 October 2026
        '%d %b %Y'     # 29 Oct 2026
    ]

    for fmt in formats_to_try:
        try:
            return datetime.strptime(date_str, fmt).strftime('%Y-%m-%d')
        except ValueError:
            continue

    return "Unknown Date"

def scrape_toi_articles(query, target_count=200):
    # Headers to mimic a real browser and prevent 403 Forbidden errors
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/115.0.0.0 Safari/537.36"
    }

    articles_data = []
    scraped_urls = set()

    articles = get_toi_articles(f'/topic/{query}/news', row=target_count)
    print(f"Fetched {len(articles)} articles successfully.")

    links = [article["wu"] for article in articles]
    print("Total Links : ", len(links))

    for link in links:
        if len(articles_data) >= target_count:
            break

        try:
            # Fetch individual article
            art_resp = requests.get(link, headers=headers)
            art_soup = BeautifulSoup(art_resp.text, 'html.parser')

            # Extract Title
            title_tag = art_soup.find('h1')
            title = title_tag.text.strip() if title_tag else "No Title"

            # Extract Text
            article_body = art_soup.find('div', class_='_s30J clearfix') or art_soup.find('div', attrs={'data-articlebody': '1'})
            if article_body:
                text = article_body.get_text(separator=' ', strip=True)
            else:
                # Fallback: gather all paragraph tags
                paragraphs = art_soup.find_all('p')
                text = " ".join([p.text.strip() for p in paragraphs if p.text.strip()])

            # Skip if no content is found
            if not text or len(text) < 50:
                continue

            # Extract Date
            byline_div = art_soup.find('div', class_='Lf73Q byline')
            if byline_div and byline_div.find('span'):
                raw_date = byline_div.find('span').text.strip()
                date = clean_and_parse_date(raw_date)
            else:
                date = "Unknown Date"

            # Extract Author
            if byline_div and byline_div.find('a'):
                author = byline_div.find('a').text.strip()
            else:
                author = "TOI Sports Desk"

            # Compile dictionary with requested columns
            articles_data.append({
                "title": title,
                "text": text,
                "published_date": date,
                "record_id": str(uuid.uuid4()),
                "url": link,
                "author": author,
                "source_type": "news_article",
                "source": "The Times of India",
                "scraped_at": datetime.now().isoformat(),
                "query": query,
                "language": "english"
            })

            print(f"Scraped {len(articles_data)}/{target_count}: {title} (Date: {date})")
            time.sleep(1)

        except Exception as e:
            print(f"Error scraping {link}: {e}")

    # Convert to Pandas DataFrame
    df = pd.DataFrame(articles_data)
    return df

