import requests

def get_toi_articles(path: str = "/topic/bricks-2026/news", row: int = 200, curpg: int = 1) -> list:
    """
    Fetches articles from the Times of India topic API.

    Parameters:
        path (str): The topic path (e.g., '/topic/bricks-2026/news').
        row (int): Number of rows/items per page.
        curpg (int): Current page number.

    Returns:
        list: A list of article dictionaries extracted from contentsData['items'].
    """
    base_url = "https://toiutils.indiatimes.com/search/treact/feeds/toi/web/show/topic"

    params = {
        "path": path,
        "row": row,
        "curpg": curpg
    }

    # Adding a standard User-Agent to prevent getting blocked by basic anti-bot filters
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
    }

    try:
        response = requests.get(base_url, params=params, headers=headers, timeout=10)
        response.raise_for_status()  # Raises HTTPError for bad responses (4xx or 5xx)

        data = response.json()

        # Navigate through the JSON schema to extract the articles list
        articles = data.get("contentsData", {}).get("items", [])
        return articles

    except requests.exceptions.RequestException as e:
        print(f"An error occurred while fetching the articles: {e}")
        return []

